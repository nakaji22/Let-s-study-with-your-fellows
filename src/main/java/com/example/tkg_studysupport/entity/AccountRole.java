package com.example.tkg_studysupport.entity;

/* 列挙型のenumを用いる. 名前と型を対応付けたいときに便利. */
/**
 * アカウントの種類を表す列挙型。
 * <p>
 * 生徒用アカウントと講師用アカウントを区別し、
 * ログイン後に利用可能な機能や画面を切り替えるために使用する。
 * </p>
 */
public enum AccountRole {
    /**
     * 生徒アカウント。
     * 勉強時間の記録、コミュニティへの参加、掲示板の閲覧が可能。
     */
    STUDENT,
    /**
     * 講師アカウント。
     * コミュニティの作成、生徒の記録閲覧、コメント投稿が可能。
     */
    OWNER
}
